_CACHE = {}
def interp(mat, EkeV, col=1):
    """log-log插值, col: 1=mu/rho, 2=muen/rho; EkeV可为数组"""
    key = (mat, col)
    if key not in _CACHE:
        d = np.array(MU[mat])
        # 处理吸收边重复能量点: 按能量排序, 同能量保留后一个(边后)
        xs, ys = d[:,0], d[:,col]
        _CACHE[key] = (xs, ys)
    xs, ys = _CACHE[key]
    x = np.asarray(EkeV, dtype=float)/1000.0
    out = np.interp(np.log(x), np.log(xs), np.log(ys),
                    left=np.log(ys[0]), right=np.log(ys[-1]))
    return np.exp(out)

# 默认(原始)模型参数
# d0: 靶自吸收等效厚度(cm); a,b: 相对低能修正强度/拐点比例;
# cAbs,E0: 绝对能量低能修正(与kVp无关); cK: 特征线强度; inhBe: Be窗等效Al(mm)
DEFAULT_P = dict(d0=0.002, a=0.5, b=0.3, cAbs=0.0, E0=8.0, cK=0.12, inhBe=0.1, sigma=0.8)

# ===== 整数keV(1..400)全局查表, 加速拟合 =====
_EG = np.arange(1, 401, 1.0)
_TAB = {}
for _m in ['Al','Cu','Sn','Pb','W']:
    _TAB[(_m,1)] = interp(_m, _EG, 1)
_TAB[('Air',2)] = interp('Air', _EG, 2)

def spectrum(kvp, ang=20.0, inh=0.1, fAl=0.0, fCu=0.0, fSn=0.0, fPb=0.0, p=None):
    """返回 E(keV数组), 过滤后光子注量谱 pF, 初始谱 p0"""
    if p is None: p = DEFAULT_P
    n = int(np.floor(kvp))
    E = _EG[:n]
    cosA = np.cos(np.deg2rad(ang))
    dSelf = p['d0']/cosA
    br = 74.0*(kvp-E); br[br<0] = 0
    sa = np.exp(-_TAB[('W',1)][:n]*RHO['W']*dSelf)
    knee = p['b']*kvp
    sh = np.where(E < knee, 1 + p['a']*(1 - E/knee), 1.0)
    sh = sh*(1 + p['cAbs']*np.exp(-E/p['E0']))
    v = br*sa*sh
    if kvp > 69.5:
        cf = p['cK']*(1 - 69.5/kvp)
        cs = kvp*cf/4.0
        for El, w in [(59.32,1),(57.98,0.52),(67.24,0.28),(69.07,0.08)]:
            v += cs*w*np.exp(-0.5*(E-El)**2/(p['sigma']**2))
    p0 = v
    at = _TAB[('Al',1)][:n]*RHO['Al']*(inh/10.0)
    if fAl>0: at += _TAB[('Al',1)][:n]*RHO['Al']*(fAl/10.0)
    if fCu>0: at += _TAB[('Cu',1)][:n]*RHO['Cu']*(fCu/10.0)
    if fSn>0: at += _TAB[('Sn',1)][:n]*RHO['Sn']*(fSn/10.0)
    if fPb>0: at += _TAB[('Pb',1)][:n]*RHO['Pb']*(fPb/10.0)
    pF = v*np.exp(-at)
    return E, p0, pF

def _wt(E):
    return E*_TAB[('Air',2)][:len(E)]*RHO['Air']

def _kerma(E, phi):
    return np.sum(phi*_wt(E))  # dE=1可约去

def hvl_material(kvp, fCu, fSn, fPb):
    """与ISO 4037表一致: >=80kVp一律Cu; 50-79kVp有金属滤片用Cu; 其余Al"""
    if kvp >= 80: return 'Cu'
    return 'Cu' if (kvp >= 50 and (fCu+fSn+fPb) > 0) else 'Al'

def transmission(E, pF, mat, t_mm, Kf=None, w=None):
    if Kf is None: Kf = _kerma(E, pF)
    if w is None: w = _wt(E)
    a = _TAB[(mat,1)][:len(E)]*RHO[mat]*(t_mm/10.0)
    return np.sum(pF*np.exp(-a)*w)/Kf

def find_hvl(E, pF, mat, frac=0.5, Kf=None, w=None, mu=None):
    lo, hi = 0.0, 0.001
    def tr(t):
        a = mu*RHO[mat]*(t/10.0)
        return np.sum(pF*np.exp(-a)*w)/Kf
    while tr(hi) > frac and hi < 5000:
        hi *= 1.5
    for _ in range(35):
        m = (lo+hi)/2
        if tr(m) > frac: lo = m
        else: hi = m
    return (lo+hi)/2

def calc(case, p=None):
    """case: dict(kvp,ang,inh,fAl,fCu,fSn,fPb); 返回 hv1,hv2(第二半值层厚度增量),hc,meanE,meanEp"""
    E, p0, pF = spectrum(p=p, **case)
    mat = hvl_material(case['kvp'], case.get('fCu',0), case.get('fSn',0), case.get('fPb',0))
    w = _wt(E); Kf = np.sum(pF*w); mu = _TAB[(mat,1)][:len(E)]
    hv1 = find_hvl(E, pF, mat, 0.5, Kf, w, mu)
    t25 = find_hvl(E, pF, mat, 0.25, Kf, w, mu)
    hv2 = t25 - hv1
    hc = hv1/hv2 if hv2 > 0 else 0
    sp, sep, se2p = pF.sum(), (E*pF).sum(), (E*E*pF).sum()
    eF = sep/sp; eP = se2p/sep
    n = len(E)
    mx = pF.max(); half = mx/2; eLo=eHi=-1
    for i in range(1,n):
        if pF[i-1] < half <= pF[i]:
            fr=(half-pF[i-1])/(pF[i]-pF[i-1]); eLo=E[i-1]+fr
        if pF[i-1] >= half > pF[i] and eLo>0:
            fr=(pF[i-1]-half)/(pF[i-1]-pF[i]); eHi=E[i-1]+fr; break
    fwhm=(eHi-eLo) if eLo>0 and eHi>0 else 0
    res = fwhm/eF*100 if eF>0 else 0
    return dict(mat=mat, hv1=hv1, hv2=hv2, hc=hc, eF=eF, eP=eP, res=res)

